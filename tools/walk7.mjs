import { open, BASE, sleep } from './pw.mjs';
const H = +process.env.VH || 844;
const { browser, page, errors } = await open({ viewport: { width: 390, height: H } });
const T = process.env.TAG || 'r1';
const shot = (n) => page.screenshot({ path: `shots/${T}-a7-${n}.png` });
await page.goto(BASE + '/index.html?act=7'); await sleep(2600);
await shot('0-dark');
await page.click('.a7-lamp[data-l="0"]'); await sleep(1700); await shot('1-lamp1');
await page.click('.a7-lamp[data-l="1"]'); await sleep(1700); await shot('2-lamp2');
await page.click('.a7-lamp[data-l="2"]'); await sleep(3600); await shot('3-lit');
await page.waitForSelector('.a7-candle:not([hidden])'); await sleep(300);
await page.click('.a7-candle[data-c="0"]'); await sleep(600); await shot('4-candle1');
await page.click('.a7-candle[data-c="1"]'); await sleep(3500); await shot('5-blessing');
await sleep(9000); await shot('6-final');
await page.waitForSelector('.a7-actions:not([hidden])', { timeout: 20000 }); await sleep(1800); await shot('7-actions');
await page.click('[data-a=album]'); await sleep(900); await shot('8-album');
await page.evaluate(() => { document.querySelector('.album-in').scrollTop = 1500; }); await sleep(500); await shot('9-album2');
await page.click('.al-close'); await sleep(500);
await page.click('[data-a=card]'); await sleep(2500); await shot('10-keepsake');
const src = await page.evaluate(() => { const im = document.querySelector('.keep-img img'); return im ? im.src.slice(0, 30) + ' len=' + im.src.length : 'none'; });
console.log('keepsake:', src);
const data = await page.evaluate(() => { const im = document.querySelector('.keep-img img'); return im ? im.src : ''; });
if (data) (await import('node:fs')).writeFileSync(`shots/${T}-keepsake.png`, Buffer.from(data.split(',')[1], 'base64'));
console.log(errors.join('\n') || 'no errors');
await browser.close();
